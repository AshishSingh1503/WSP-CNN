"""Regenerate every table and figure from the saved results.

  python scripts/reproduce_tables.py            # write results/tables/*, results/figures/* and manifest.json
  python scripts/reproduce_tables.py --check    # regenerate into a scratch folder and fail if anything differs
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from src.analysis.reproduce import check, default_predictions, reproduce  # noqa: E402
from src.utils.config import load_config  # noqa: E402


def main() -> int:
    """Run the reproduction (or the identity check)."""
    p = argparse.ArgumentParser(description="Regenerate all tables and figures from saved results")
    p.add_argument("--check", action="store_true", help="compare a fresh regeneration with the stored manifest")
    args = p.parse_args()
    cfg = load_config()
    preds = default_predictions(cfg)
    if args.check:
        with tempfile.TemporaryDirectory() as scratch:
            diff = check(cfg, preds, Path(scratch))
        print("IDENTICAL: every table and figure regenerated byte for byte" if not diff else f"DIFFERENT: {diff}")
        return 1 if diff else 0
    manifest = reproduce(cfg, preds)
    print(f"wrote {len(manifest)} files; manifest at results/tables/manifest.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
