"""Write results/tables/*.csv and results.md. All numbers are formatted from computed frames, never typed."""
from __future__ import annotations

import math
from pathlib import Path
from typing import Any

import pandas as pd

from src.analysis.stats import Predictions, build_all
from src.utils.config import Config, resolve_path


def md_table(df: pd.DataFrame, floats: int = 2) -> str:
    """GitHub-flavoured markdown table from a DataFrame (NaN shown as an en dash)."""
    def fmt(v: Any) -> str:
        if isinstance(v, bool):
            return "yes" if v else "no"
        if isinstance(v, float):
            return "–" if math.isnan(v) else (f"{v:.{floats}e}" if (v != 0 and abs(v) < 10 ** -floats) else f"{v:.{floats}f}")
        return str(v)
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "---|" * len(df.columns)
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *body])


def comparison_frames(res: dict[str, Any]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """(per-seed rows, across-seed summaries) for every comparison."""
    per_seed = pd.concat([c.per_seed.assign(comparison=cid, a=c.a, b=c.b) for cid, c in res["comparisons"].items()], ignore_index=True)
    summary = pd.DataFrame([{"comparison": cid, "a": c.a, "b": c.b, **c.summary} for cid, c in res["comparisons"].items()])
    return per_seed, summary


def pc_summary(pc: pd.DataFrame) -> pd.DataFrame:
    """Per fault and method: mean over seeds of drop, recovery (test and validation) and localisation."""
    g = pc.groupby(["fault", "method"], sort=False)
    return g.agg(test_drop_pp=("test_drop_pp", "mean"), test_recovery=("test_recovery", "mean"), val_recovery=("val_recovery", "mean"),
                 edited_scalars=("edited_scalars", "mean"), precision=("precision", "mean"), recall=("recall", "mean"),
                 successes=("success", "sum"), runs=("success", "size")).reset_index()


def arm_overview(cfg: Config, res: dict[str, Any]) -> pd.DataFrame:
    """The main results table: test accuracy, change vs E0, edit size and cost per arm."""
    acc, costs = res["accuracy"].set_index("arm"), res["costs"]
    base = acc.loc["E0", "mean_acc"]
    rows = []
    for arm in cfg.analysis.arms:
        c = costs[costs["arm"] == arm]
        rows.append({"arm": cfg.analysis.arm_labels[arm], "test_acc_%": acc.loc[arm, "mean_acc"], "sd_over_seeds": acc.loc[arm, "sd_acc"],
                     "vs_E0_pp": acc.loc[arm, "mean_acc"] - base, "macro_F1_%": acc.loc[arm, "mean_macro_f1"],
                     "changed_scalars": float(c["changed_scalars"].mean()), "rel_norm": float(c["rel_norm"].mean()),
                     "llm_usd_per_seed": float(c["llm_usd"].mean())})
    return pd.DataFrame(rows)


def write_tables(cfg: Config, preds: Predictions, out_dir: Path | None = None, seeds: list[int] | None = None) -> dict[str, Any]:
    """Compute everything and write the CSVs plus results.md; returns the computed frames."""
    out = out_dir or resolve_path(cfg.analysis.tables_dir)
    out.mkdir(parents=True, exist_ok=True)
    res = build_all(cfg, preds, seeds)
    per_seed, summary = comparison_frames(res)
    overview, pcs = arm_overview(cfg, res), pc_summary(res["pc"])
    frames = {"arm_accuracy": res["accuracy"], "arm_overview": overview, "primary_claims": res["primary"],
              "per_seed_comparisons": per_seed, "comparison_summary": summary, "efficiency": res["efficiency"],
              "run_costs": res["costs"], "pc_runs": res["pc"], "pc_summary": pcs}
    for name, df in frames.items():
        df.to_csv(out / f"{name}.csv", index=False, float_format="%.10g")
    p_d = res["p_d"]
    text = "\n\n".join([
        "<!-- generated by scripts/reproduce_tables.py from results/test/*, results/*/summary.json and results/PC/*; do not edit -->",
        f"# Results tables (test set, seeds {', '.join(map(str, res['seeds']))})",
        "## Arms (test accuracy, mean over seeds)\n\n" + md_table(overview),
        "## Primary claims (Holm-corrected over P-a, P-b, P-c, P-d)\n\n" + md_table(res["primary"], 4),
        f"P-d: {p_d['successes']} of {p_d['runs']} Pure-WSP positive-control runs recovered at least the required fraction of the drop "
        f"(exact one-sided binomial test against a null rate of {p_d['null_rate']}, p = {p_d['p_one_sided']:.4g}; "
        f"{p_d['excluded_runs']} runs excluded by the fault-drop precondition).",
        "## Exploratory comparisons (unadjusted)\n\n" + md_table(summary, 4),
        "## Per-seed paired differences (pp), bootstrap 95% CI and exact McNemar\n\n" + md_table(per_seed, 4),
        "## Parameter efficiency (gain over E0)\n\n" + md_table(res["efficiency"], 4),
        "## Positive control (mean over seeds)\n\n" + md_table(pcs, 3),
        "## Per-run cost\n\n" + md_table(res["costs"], 3),
        "Notes: with 5 seeds the Wilcoxon test cannot reach p below 0.0625 (two-sided) and the across-seed t-interval has 4 degrees of freedom; "
        "both are low-power. E4 values are means over its random edit sets and have no McNemar test.",
    ])
    (out / "results.md").write_text(text + "\n", encoding="utf-8")
    return {**res, "frames": frames}
